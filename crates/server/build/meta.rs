//! Build identity: `$OUT_DIR/build_info.rs` with the version, commit, build time and target.

use std::{
    env, fs,
    path::Path,
    time::{SystemTime, UNIX_EPOCH},
};

use crate::{Result, civil};

pub(crate) fn generate(out_dir: &Path) -> Result<()> {
    for var in ["UNIWRT_VERSION", "UNIWRT_COMMIT", "SOURCE_DATE_EPOCH"] {
        println!("cargo::rerun-if-env-changed={var}");
    }
    let version = input("UNIWRT_VERSION")?.unwrap_or_else(|| "0.0.0-dev".to_owned());
    let commit = input("UNIWRT_COMMIT")?.unwrap_or_else(|| "unknown".to_owned());
    let built_at = civil::rfc3339_utc(build_time()?);
    let target = env::var("TARGET")?;
    let code = format!(
        "// @generated by crates/server/build/meta.rs. Do not edit.\n\
         pub(crate) const VERSION: &str = {version:?};\n\
         pub(crate) const COMMIT: &str = {commit:?};\n\
         pub(crate) const BUILT_AT: &str = {built_at:?};\n\
         pub(crate) const TARGET: &str = {target:?};\n"
    );
    fs::write(out_dir.join("build_info.rs"), code)?;
    Ok(())
}

/// An optional build input. Values reach logs and HTTP responses, so they must be short and
/// printable ASCII; anything else fails the build instead of shipping a mangled identity.
fn input(name: &str) -> Result<Option<String>> {
    let value = match env::var(name) {
        Ok(value) if !value.is_empty() => value,
        Ok(_) | Err(env::VarError::NotPresent) => return Ok(None),
        Err(err) => return Err(format!("{name}: {err}").into()),
    };
    if value.len() > 64 || !value.bytes().all(|b| b.is_ascii_graphic()) {
        return Err(
            format!("{name}={value:?}: expected at most 64 printable ASCII characters").into(),
        );
    }
    Ok(Some(value))
}

/// Seconds since the Unix epoch: `SOURCE_DATE_EPOCH` for reproducible builds, otherwise now.
fn build_time() -> Result<u64> {
    match input("SOURCE_DATE_EPOCH")? {
        Some(secs) => secs
            .parse()
            .map_err(|err| format!("SOURCE_DATE_EPOCH={secs:?}: {err}").into()),
        None => Ok(SystemTime::now().duration_since(UNIX_EPOCH)?.as_secs()),
    }
}
