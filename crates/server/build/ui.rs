//! Embeds the web UI: every file plus brotli and gzip variants, and a lookup table sorted by path
//! (`$OUT_DIR/ui.rs`, included by `src/ui/assets.rs`).

use std::{
    env,
    fmt::Write as _,
    fs,
    io::Write as _,
    path::{Path, PathBuf},
};

use flate2::{Compression, write::GzEncoder};
use sha2::{Digest as _, Sha256};

use crate::Result;

/// Vite writes content-hashed files here (`build.assetsDir`), so they can be cached forever.
const HASHED_DIR: &str = "assets/";

struct File {
    /// Relative to the UI root, `/`-separated, without a leading slash.
    path: String,
    bytes: Vec<u8>,
}

pub(crate) fn generate(manifest_dir: &Path, out_dir: &Path) -> Result<()> {
    let (root, placeholder) = locate(manifest_dir)?;
    let mut files = Vec::new();
    collect(&root, &root, &mut files)?;
    files.sort_by(|a, b| a.path.cmp(&b.path));
    let index = files
        .iter()
        .position(|file| file.path == "index.html")
        .ok_or_else(|| format!("{} has no index.html", root.display()))?;

    let blobs = out_dir.join("ui");
    if blobs.exists() {
        fs::remove_dir_all(&blobs)?;
    }
    fs::create_dir_all(&blobs)?;

    let source = if placeholder {
        "Placeholder"
    } else {
        "WebDist"
    };
    let mut table = format!(
        "// @generated by crates/server/build/ui.rs from {:?}. Do not edit.\n\
         pub(crate) static EMBEDDED: Assets = Assets {{\n    \
         source: Source::{source},\n    hashed_dir: {HASHED_DIR:?},\n    index: {index},\n    \
         files: &[\n",
        root.display().to_string(),
    );
    for (n, file) in files.iter().enumerate() {
        let (content_type, compressible) = content_type(&file.path);
        let hash = short_hash(&file.bytes);
        let identity = variant(&blobs, &n.to_string(), &file.bytes, &format!("\"{hash}\""))?;
        let (br, gz) = if compressible {
            (
                worthwhile(brotli(&file.bytes)?, file.bytes.len()),
                worthwhile(gzip(&file.bytes)?, file.bytes.len()),
            )
        } else {
            (None, None)
        };
        let optional = |bytes: Option<Vec<u8>>, suffix: &str| -> Result<String> {
            bytes.map_or_else(
                || Ok("None".to_owned()),
                |bytes| {
                    let etag = format!("\"{hash}-{suffix}\"");
                    Ok(format!(
                        "Some({})",
                        variant(&blobs, &format!("{n}.{suffix}"), &bytes, &etag)?
                    ))
                },
            )
        };
        write!(
            table,
            "        Asset {{\n            path: {:?},\n            content_type: {content_type:?},\n            \
             identity: {identity},\n            brotli: {},\n            gzip: {},\n        }},\n",
            file.path,
            optional(br, "br")?,
            optional(gz, "gz")?,
        )?;
    }
    table.push_str("    ],\n};\n");
    fs::write(out_dir.join("ui.rs"), table)?;
    Ok(())
}

/// Picks the UI to embed: `UNIWRT_WEB_DIST` (relative to the workspace root; it must hold
/// `index.html`), else `web/dist` when it has been built, else the placeholder page.
fn locate(manifest_dir: &Path) -> Result<(PathBuf, bool)> {
    println!("cargo::rerun-if-env-changed=UNIWRT_WEB_DIST");
    let workspace = manifest_dir
        .parent()
        .and_then(Path::parent)
        .ok_or("the crate must live at <workspace>/crates/server")?;
    if let Some(dir) = env::var_os("UNIWRT_WEB_DIST").filter(|dir| !dir.is_empty()) {
        let dist = workspace.join(dir);
        println!("cargo::rerun-if-changed={}", dist.display());
        if !dist.join("index.html").is_file() {
            return Err(format!("UNIWRT_WEB_DIST: {} has no index.html", dist.display()).into());
        }
        return Ok((dist, false));
    }
    let dist = workspace.join("web/dist");
    // Watched even while missing: cargo then reruns this script on every build until the UI has
    // been built, so a fresh `web/dist` is never silently ignored.
    println!("cargo::rerun-if-changed={}", dist.display());
    if dist.join("index.html").is_file() {
        return Ok((dist, false));
    }
    if dist.exists() {
        println!(
            "cargo::warning={} has no index.html; embedding the placeholder",
            dist.display()
        );
    }
    let placeholder = manifest_dir.join("placeholder");
    println!("cargo::rerun-if-changed={}", placeholder.display());
    Ok((placeholder, true))
}

/// Gathers the files under `dir`, skipping dotfiles (such as `.vite/`) and precompressed copies.
fn collect(root: &Path, dir: &Path, files: &mut Vec<File>) -> Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
            return Err(format!("{}: UI file names must be UTF-8", path.display()).into());
        };
        let precompressed = path
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("br") || ext.eq_ignore_ascii_case("gz"));
        if name.starts_with('.') || precompressed {
            continue;
        }
        if fs::metadata(&path)?.is_dir() {
            collect(root, &path, files)?;
        } else {
            let relative = path
                .strip_prefix(root)?
                .to_str()
                .ok_or("non-UTF-8 path")?
                .to_owned();
            files.push(File {
                bytes: fs::read(&path)?,
                path: relative,
            });
        }
    }
    Ok(())
}

/// The `Content-Type` for a file name, and whether compressing it pays off.
fn content_type(path: &str) -> (&'static str, bool) {
    let extension = path
        .rsplit_once('.')
        .map_or("", |(_, ext)| ext)
        .to_ascii_lowercase();
    match extension.as_str() {
        "html" => ("text/html; charset=utf-8", true),
        "js" | "mjs" => ("text/javascript; charset=utf-8", true),
        "css" => ("text/css; charset=utf-8", true),
        "json" | "map" => ("application/json", true),
        "webmanifest" => ("application/manifest+json", true),
        "svg" => ("image/svg+xml", true),
        "txt" => ("text/plain; charset=utf-8", true),
        "xml" => ("application/xml", true),
        "wasm" => ("application/wasm", true),
        "ico" => ("image/x-icon", true),
        "ttf" => ("font/ttf", true),
        "otf" => ("font/otf", true),
        "png" => ("image/png", false),
        "jpg" | "jpeg" => ("image/jpeg", false),
        "gif" => ("image/gif", false),
        "webp" => ("image/webp", false),
        "avif" => ("image/avif", false),
        "woff" => ("font/woff", false),
        "woff2" => ("font/woff2", false),
        _ => ("application/octet-stream", false),
    }
}

/// The first 64 bits of the SHA-256, in hex: the content part of every `ETag`.
fn short_hash(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .take(8)
        .fold(String::with_capacity(16), |mut hex, byte| {
            let _ = write!(hex, "{byte:02x}");
            hex
        })
}

/// Writes one representation to `$OUT_DIR/ui/<name>` and returns its `Variant` expression.
fn variant(blobs: &Path, name: &str, bytes: &[u8], etag: &str) -> Result<String> {
    fs::write(blobs.join(name), bytes)?;
    Ok(format!(
        "Variant {{ etag: {etag:?}, bytes: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/ui/{name}\")) }}"
    ))
}

/// Keeps a compressed variant only when it saves at least 10%.
fn worthwhile(compressed: Vec<u8>, original: usize) -> Option<Vec<u8>> {
    (compressed.len() * 10 < original * 9).then_some(compressed)
}

fn brotli(bytes: &[u8]) -> Result<Vec<u8>> {
    let params = brotli::enc::BrotliEncoderParams {
        quality: 11,
        size_hint: bytes.len(),
        ..Default::default()
    };
    let mut out = Vec::new();
    brotli::enc::BrotliCompress(&mut &bytes[..], &mut out, &params)?;
    Ok(out)
}

fn gzip(bytes: &[u8]) -> Result<Vec<u8>> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::best());
    encoder.write_all(bytes)?;
    Ok(encoder.finish()?)
}
