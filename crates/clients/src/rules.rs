//! The device-kind rules ([`classify`](crate::classify)), in order: the first that matches
//! wins, so specific rules come before broad ones (a tablet's "galaxy-tab" before a phone's
//! "galaxy", a camera's "-cam" before the smart home's "esp32"). Hostnames are matched in
//! lowercase: `contains` anywhere, `prefixes` at the start, `words` as whole words between
//! punctuation. Vendors are the normalized names of `data/oui.bin`, matched as their first
//! words.

use crate::ClientKind;

pub(crate) struct Rule {
    pub(crate) kind: ClientKind,
    pub(crate) contains: &'static [&'static str],
    pub(crate) prefixes: &'static [&'static str],
    pub(crate) words: &'static [&'static str],
}

const fn rule(
    kind: ClientKind,
    contains: &'static [&'static str],
    prefixes: &'static [&'static str],
    words: &'static [&'static str],
) -> Rule {
    Rule {
        kind,
        contains,
        prefixes,
        words,
    }
}

