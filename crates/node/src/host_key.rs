//! Host keys: what a node presents in the handshake, checked against the pin the controller
//! keeps from adoption (trust on first use).

use std::{fmt, sync::Arc};

use russh::keys::{HashAlg, PublicKey};
use uniwrt_core::Timestamp;
use uniwrt_model::node::HostKeyPin;

use crate::{Error, Result};

/// A node's SSH host key. Two keys are equal when their key material is, whatever the comment.
/// `Display` and `Debug` show the algorithm and the SHA-256 fingerprint.
#[derive(Clone)]
pub struct HostKey(Arc<Inner>);

struct Inner {
    key: PublicKey,
    openssh: String,
    fingerprint: String,
}

impl HostKey {
    /// Reads the OpenSSH form, `ssh-ed25519 AAAA…` (a trailing comment is ignored).
    pub fn parse(openssh: &str) -> Result<Self> {
        let key = PublicKey::from_openssh(openssh).map_err(|source| Error::Key {
            what: "host key",
            source,
        })?;
        Self::new(key)
    }

    pub(crate) fn new(mut key: PublicKey) -> Result<Self> {
        key.set_comment("");
        let openssh = key.to_openssh().map_err(|source| Error::Key {
            what: "host key",
            source,
        })?;
        let fingerprint = key.fingerprint(HashAlg::Sha256).to_string();
        Ok(Self(Arc::new(Inner {
            key,
            openssh,
            fingerprint,
        })))
    }

    /// The OpenSSH form without a comment.
    pub fn to_openssh(&self) -> &str {
        &self.0.openssh
    }

    /// The SHA-256 fingerprint as OpenSSH shows it, `SHA256:…`: what the user confirms.
    pub fn fingerprint(&self) -> &str {
        &self.0.fingerprint
    }

    /// The algorithm name, such as `ssh-ed25519`.
    pub fn algorithm(&self) -> String {
        self.0.key.algorithm().to_string()
    }

    pub fn pin(&self, at: Timestamp) -> HostKeyPin {
        HostKeyPin {
            public_key: self.0.openssh.clone(),
            fingerprint: self.0.fingerprint.clone(),
            pinned_at: at,
        }
    }

    pub fn from_pin(pin: &HostKeyPin) -> Result<Self> {
        Self::parse(&pin.public_key)
    }

    pub(crate) fn matches(&self, key: &PublicKey) -> bool {
        self.0.key.key_data() == key.key_data()
    }
}

impl PartialEq for HostKey {
    fn eq(&self, other: &Self) -> bool {
        self.matches(&other.0.key)
    }
}

impl Eq for HostKey {}

impl fmt::Display for HostKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} {}", self.0.key.algorithm(), self.0.fingerprint)
    }
}

impl fmt::Debug for HostKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "HostKey({self})")
    }
}

#[cfg(test)]
mod tests {
    use uniwrt_core::Timestamp;

    use super::HostKey;

    // Generated by dropbear 2025.89 in the OpenWrt 25.12.6 rootfs.
    const KEY: &str =
        "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIBWCwQCJkKENr7v1OmtQx20yykz6eObDLwYTiz0mnRir";
    const FINGERPRINT: &str = "SHA256:b4fj9KwrdrZf3YWj+/rWT8wXa6mEIz2kduZrGFi1xFY";

    #[test]
    fn parses_pins_and_compares_by_key_material() {
        let key = HostKey::parse(&format!("{KEY} root@OpenWrt")).unwrap();
        assert_eq!(key.to_openssh(), KEY);
        assert_eq!(key.algorithm(), "ssh-ed25519");
        // As dropbear logged it.
        assert_eq!(key.fingerprint(), FINGERPRINT);
        assert_eq!(
            key.to_string(),
            format!("ssh-ed25519 {}", key.fingerprint())
        );

        let pin = key.pin(Timestamp::from_unix_ms(5));
        assert_eq!(pin.public_key, KEY);
        assert_eq!(pin.fingerprint, key.fingerprint());
        assert_eq!(HostKey::from_pin(&pin).unwrap(), key);
        assert_eq!(HostKey::parse(KEY).unwrap(), key);
    }

    #[test]
    fn garbage_is_refused() {
        assert!(HostKey::parse("ssh-ed25519 not-base64").is_err());
        assert!(HostKey::parse("").is_err());
    }
}
