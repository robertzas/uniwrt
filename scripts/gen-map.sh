#!/usr/bin/env bash
# Regenerates docs/MAP.md, the code map: each Rust file with the first sentence of its `//!`
# header, the web UI's directories and the scripts. With --check it only reports staleness.
# Markdown backticks inside single quotes are literal on purpose.
# shellcheck disable=SC2016
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."

map=docs/MAP.md

# Tracked plus untracked, non-ignored files, so a new file is mapped before its first commit.
files() {
  git ls-files --cached --others --exclude-standard -- "$@" | sort -u | while IFS= read -r f; do
    if [[ -f $f ]]; then printf '%s\n' "$f"; fi
  done
}

# The first sentence of a file's leading comment block, joined across wrapped lines. $2 is the
# comment marker: `//!` for Rust, `#` for scripts (a shebang line is skipped).
summary() {
  awk -v marker="$2" '
    NR == 1 && /^#!/ { next }
    index($0, marker) == 1 {
      line = substr($0, length(marker) + 1)
      sub(/^ /, "", line)
      if (line == "") { if (text != "") exit; next }
      text = text (text == "" ? "" : " ") line
      next
    }
    { exit }
    END {
      if (text == "") text = "(no header comment)"
      else if (match(text, /\. [A-Z`]/)) text = substr(text, 1, RSTART)
      print text
    }' "$1"
}

rust() {
  printf '\n## Rust crates\n\nA crate'\''s contract is the full `//!` header of its `lib.rs` or `main.rs`.\n'
  files ':(glob)crates/*/Cargo.toml' | while IFS= read -r manifest; do
    local dir=${manifest%/Cargo.toml} name root about="(no lib.rs or main.rs)"
    name=$(awk -F'"' '/^name *=/ { print $2; exit }' "$manifest")
    for root in "$dir/src/lib.rs" "$dir/src/main.rs"; do
      if [[ -f $root ]]; then about=$(summary "$root" '//!') && break; fi
    done
    printf '\n### `%s` (%s)\n\n%s\n\n' "$name" "$dir" "$about"
    files ":(glob)$dir/**/*.rs" | while IFS= read -r f; do
      printf -- '- `%s`: %s\n' "${f#"$dir"/}" "$(summary "$f" '//!')"
    done
  done
}

web() {
  printf '\n## Web UI (`web/src`)\n\nFiles per directory. Tests sit next to the code as `*.test.ts[x]`; `test/` holds the shared setup.\n\n'
  files ':(glob)web/src/**' | grep -Ev '\.test\.tsx?$|^web/src/test/' | awk '
    {
      path = substr($0, length("web/src/") + 1)
      slash = 0
      for (i = length(path); i > 0; i--) if (substr(path, i, 1) == "/") { slash = i; break }
      print substr(path, 1, slash) "\t" substr(path, slash + 1)
    }' | sort -t "$(printf '\t')" -k1,1 -k2,2 | awk -F'\t' '
    function flush() {
      if (dir == "") print "- top level: " list
      else if (dir ~ /^api\/gen\//) print "- `" dir "`: TypeScript types generated from Rust DTOs by `just gen` (" count (count == 1 ? " file" : " files") "); never edit"
      else print "- `" dir "`: " list
    }
    NR > 1 && $1 != dir { flush(); list = ""; count = 0 }
    { dir = $1; list = list (count++ ? ", " : "") $2 }
    END { if (NR) flush() }'
}

agent() {
  printf '\n## Node agent (`node-agent`)\n\nucode modules, embedded in the binary and installed on nodes by hash (`crates/node/src/bundle.rs`). The entry point is `main.uc`.\n\n'
  files ':(glob)node-agent/**/*.uc' | while IFS= read -r f; do
    printf -- '- `%s`: %s\n' "${f#node-agent/}" "$(summary "$f" '//')"
  done
}
scripts() {
  printf '\n## Scripts\n\n'
  files ':(glob)scripts/**' | while IFS= read -r f; do
    printf -- '- `%s`: %s\n' "$f" "$(summary "$f" '#')"
  done
}

generate() {
  printf '<!-- Generated by scripts/gen-map.sh (`just map`); do not edit. `just check` refreshes it, and CI fails when it is stale. -->\n\n'
  printf '# Code map\n\nWhere code lives. Each entry is the first sentence of the file'\''s header comment; grep for symbols.\n'
  rust
  agent
  web
  scripts
}

fresh=$(generate)
if [[ ${1:-} == --check ]]; then
  if [[ $fresh == "$(cat "$map" 2>/dev/null)" ]]; then exit 0; fi
  echo "$map is stale; run \`just map\` and commit it:" >&2
  diff -u "$map" - <<<"$fresh" >&2 || true
  exit 1
fi
if [[ $fresh != "$(cat "$map" 2>/dev/null)" ]]; then
  printf '%s\n' "$fresh" >"$map"
  echo "regenerated $map"
fi
